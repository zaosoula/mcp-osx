import { z } from 'zod';
import { type Action, as, noArgs, bool } from './types.js';
import { AS_HELPERS } from './helpers.js';

/** Mail. Read-only listing/reading plus visible drafts. Never sends, replies, forwards, deletes or moves. */

const MAX_TEXT = 4000;
const NOT_RUNNING = 'if not (application id "com.apple.mail" is running) then return "Mail is not running"';

// Resolve mailbox `mb` (optionally in account `acc`) into `m`; "inbox" means the unified inbox or the account's INBOX.
const RESOLVE_MAILBOX = [
  '  set m to missing value',
  '  if acc is "" then',
  '    if mb is "inbox" then',
  '      set m to inbox',
  '    else',
  '      try',
  '        set m to mailbox mb',
  '        get name of m',
  '      on error',
  '        set m to missing value',
  '        repeat with a in every account',
  '          try',
  '            set m to mailbox mb of a',
  '            get name of m',
  '            exit repeat',
  '          on error',
  '            set m to missing value',
  '          end try',
  '        end repeat',
  '      end try',
  '    end if',
  '  else',
  '    try',
  '      set a to account acc',
  '      get name of a',
  '    on error',
  '      return "no account named " & acc',
  '    end try',
  '    try',
  '      if mb is "inbox" then',
  '        set m to mailbox "INBOX" of a',
  '      else',
  '        set m to mailbox mb of a',
  '      end if',
  '      get name of m',
  '    on error',
  '      set m to missing value',
  '    end try',
  '  end if',
  '  if m is missing value then return "no mailbox named " & mb',
];

const LIST_MESSAGES = as([
  ...AS_HELPERS,
  'on run argv',
  NOT_RUNNING,
  'set mb to item 1 of argv',
  'set acc to item 2 of argv',
  'set lim to (item 3 of argv) as integer',
  'set unreadOnly to (item 4 of argv) is "true"',
  'tell application id "com.apple.mail"',
  ...RESOLVE_MAILBOX,
  '  if unreadOnly then',
  '    set q to a reference to (every message of m whose read status is false)',
  '    set n to count of q',
  '  else',
  '    set n to count of messages of m',
  '    if n = 0 then return "no messages"',
  '    set k to lim',
  '    if n < k then set k to n',
  '    set q to a reference to (messages 1 thru k of m)',
  '  end if',
  '  if n = 0 then return "no messages"',
  '  set ds to date received of q',
  '  set ss to sender of q',
  '  set js to subject of q',
  '  set rs to read status of q',
  '  set ids to id of q',
  'end tell',
  'set out to {}',
  'repeat with i from 1 to count of ids',
  '  if i > lim then exit repeat',
  '  if item i of rs then',
  '    set rdf to "read"',
  '  else',
  '    set rdf to "unread"',
  '  end if',
  '  set end of out to my fmt(item i of ds) & tab & my cl(item i of ss) & tab & my cl(item i of js) & tab & rdf & tab & ((item i of ids) as text)',
  'end repeat',
  'set r to my joinL(out, linefeed)',
  'if n > lim then set r to r & linefeed & "(" & (n - lim) & " more not shown)"',
  'return r',
  'end run',
]);

const READ_MESSAGE = as([
  ...AS_HELPERS,
  'on run argv',
  NOT_RUNNING,
  'set mid to (item 1 of argv) as integer',
  'set mx to (item 2 of argv) as integer',
  'tell application id "com.apple.mail"',
  '  set msg to missing value',
  '  try',
  '    set msg to first message of inbox whose id is mid',
  '  end try',
  '  if msg is missing value then',
  '    repeat with a in every account',
  '      repeat with bx in every mailbox of a',
  '        try',
  '          set msg to first message of bx whose id is mid',
  '          exit repeat',
  '        end try',
  '      end repeat',
  '      if msg is not missing value then exit repeat',
  '    end repeat',
  '  end if',
  '  if msg is missing value then return "no message with id " & mid',
  '  set toL to address of every to recipient of msg',
  '  set ccL to address of every cc recipient of msg',
  '  set hdr to "From: " & my cl(sender of msg) & linefeed & "To: " & my cl(my joinL(toL, ", ")) & linefeed',
  '  if (count of ccL) > 0 then set hdr to hdr & "Cc: " & my cl(my joinL(ccL, ", ")) & linefeed',
  '  set hdr to hdr & "Date: " & my fmt(date received of msg) & linefeed & "Subject: " & my cl(subject of msg) & linefeed & "Mailbox: " & my cl(name of mailbox of msg) & linefeed & "Read: " & ((read status of msg) as text)',
  '  set t to content of msg as text',
  'end tell',
  'if (length of t) > mx then return hdr & linefeed & linefeed & (text 1 thru mx of t) & linefeed & "[truncated: " & (length of t) & " chars total, showing first " & mx & "]"',
  'return hdr & linefeed & linefeed & t',
  'end run',
]);

const UNREAD_COUNT = as([
  'on run argv',
  NOT_RUNNING,
  'set acc to item 1 of argv',
  'tell application id "com.apple.mail"',
  '  if acc is "" then return "inbox unread " & (unread count of inbox)',
  '  try',
  '    set a to account acc',
  '    get name of a',
  '  on error',
  '    return "no account named " & acc',
  '  end try',
  '  try',
  '    return acc & " INBOX unread " & (unread count of mailbox "INBOX" of a)',
  '  on error',
  '    return "no INBOX in account " & acc',
  '  end try',
  'end tell',
  'end run',
]);

// argv: subject, body, nTo, to..., nCc, cc...
const COMPOSE = as([
  'on run argv',
  'set subj to item 1 of argv',
  'set bdy to item 2 of argv',
  'set nTo to (item 3 of argv) as integer',
  'set toL to {}',
  'repeat with i from 1 to nTo',
  '  set end of toL to item (3 + i) of argv',
  'end repeat',
  'set nCc to (item (4 + nTo) of argv) as integer',
  'set ccL to {}',
  'repeat with i from 1 to nCc',
  '  set end of ccL to item (4 + nTo + i) of argv',
  'end repeat',
  'tell application id "com.apple.mail"',
  '  set msg to make new outgoing message with properties {subject:subj, content:bdy, visible:true}',
  '  tell msg',
  '    repeat with x in toL',
  '      make new to recipient at end of to recipients with properties {address:(x as text)}',
  '    end repeat',
  '    repeat with x in ccL',
  '      make new cc recipient at end of cc recipients with properties {address:(x as text)}',
  '    end repeat',
  '  end tell',
  '  activate',
  'end tell',
  'return "draft window opened (NOT sent): " & subj',
  'end run',
]);

const emails = z.array(z.email()).max(50);

export const mailActions: Action[] = [
  {
    name: 'mail_list_accounts',
    description: 'List Mail accounts: name, type, enabled, email addresses (requires Mail running).',
    schema: {},
    build: noArgs(as([
      ...AS_HELPERS,
      NOT_RUNNING,
      'set out to {}',
      'tell application id "com.apple.mail"',
      '  repeat with a in every account',
      '    set end of out to my cl(name of a) & tab & ((account type of a) as text) & tab & ((enabled of a) as text) & tab & my joinL(email addresses of a, ", ")',
      '  end repeat',
      'end tell',
      'if (count of out) = 0 then return "no accounts"',
      'return my joinL(out, linefeed)',
    ])),
  },
  {
    name: 'mail_unread_count',
    description: 'Return the unread count of the unified inbox, or of one account\'s INBOX (requires Mail running).',
    schema: { account: z.string().optional().describe('Account name (default: unified inbox)') },
    build: ({ account }) => ({ script: UNREAD_COUNT, args: [account ?? ''] }),
  },
  {
    name: 'mail_list_messages',
    description: 'List recent messages in a mailbox (default inbox): date, sender, subject, read/unread, id (requires Mail running).',
    schema: {
      mailbox: z.string().optional().describe('Mailbox name (default "inbox": unified inbox, or the account\'s INBOX)'),
      account: z.string().optional().describe('Account name'),
      limit: z.number().int().min(1).max(200).optional().describe('Max messages (default 10, max 200)'),
      unreadOnly: z.boolean().optional(),
    },
    build: ({ mailbox, account, limit, unreadOnly }) => ({
      script: LIST_MESSAGES,
      args: [mailbox ?? 'inbox', account ?? '', String(limit ?? 10), bool(!!unreadOnly)],
    }),
  },
  {
    name: 'mail_read_message',
    description: `Return a message's headers and plain-text content (truncated to ${MAX_TEXT} chars) by id from mail_list_messages (requires Mail running).`,
    schema: { id: z.number().int().min(1).describe('Message id from mail_list_messages') },
    build: ({ id }) => ({ script: READ_MESSAGE, args: [String(id), String(MAX_TEXT)] }),
  },
  {
    name: 'mail_check_new',
    description: 'Ask Mail to check all accounts for new mail (requires Mail running).',
    schema: {},
    build: noArgs(as([
      NOT_RUNNING,
      'tell application id "com.apple.mail" to check for new mail',
      'return "checking for new mail"',
    ])),
  },
  {
    name: 'mail_compose_draft',
    description: 'Open a VISIBLE new-message window in Mail prefilled with to/cc/subject/body; does NOT send (the user reviews and sends).',
    schema: {
      to: emails.optional().describe('To addresses'),
      cc: emails.optional().describe('Cc addresses'),
      subject: z.string().optional(),
      body: z.string().optional().describe('Plain-text body'),
    },
    build: ({ to = [], cc = [], subject, body }) => ({
      script: COMPOSE,
      args: [subject ?? '', body ?? '', String(to.length), ...to, String(cc.length), ...cc],
    }),
  },
];
