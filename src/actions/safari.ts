import { z } from 'zod';
import { type Action, as, noArgs, bool } from './types.js';
import { CL } from './helpers.js';

/** Safari. */
export const safariActions: Action[] = [
  {
    name: 'safari_open_url',
    description: 'Open a URL in Safari (new tab in the front window by default).',
    schema: { url: z.string().url().refine((u) => /^https?:\/\//i.test(u), 'Only http(s) URLs are allowed').describe('http(s) URL'), newWindow: z.boolean().optional() },
    build: ({ url, newWindow }) => ({
      script: as([
        'on run argv',
        'set u to item 1 of argv',
        'tell application "Safari"',
        '  activate',
        '  if (item 2 of argv) is "true" or (count of windows) = 0 then',
        '    make new document with properties {URL:u}',
        '  else',
        '    tell front window to set current tab to (make new tab with properties {URL:u})',
        '  end if',
        'end tell',
        'return "opened " & u',
        'end run',
      ]),
      args: [url, bool(!!newWindow)],
    }),
  },
  {
    name: 'safari_current_tab',
    description: 'Return the current Safari tab. Returns tab-separated: url, title.',
    schema: {},
    output: { columns: ['url', 'title'] },
    build: noArgs(as([
      ...CL,
      'if not (application "Safari" is running) then return "Safari is not running"',
      'set TB to character id 9',
      'tell application "Safari"',
      '  if (count of windows) = 0 then return "no Safari window open"',
      '  set t to current tab of front window',
      '  set u to URL of t',
      '  return my cl(u) & TB & my cl(name of t)',
      'end tell',
    ])),
  },
  {
    name: 'safari_list_tabs',
    description: 'List open Safari tabs, one per line. Returns tab-separated: window, tab (indexes), current ("*" if current tab, else empty), title, url (cut at 300 chars).',
    schema: { limit: z.number().int().min(1).max(500).optional().describe('max tabs to return (default 100)') },
    output: { columns: ['window', 'tab', 'current', 'title', 'url'] },
    build: ({ limit }) => ({
      script: as([
        'on run argv',
        'if not (application "Safari" is running) then return "Safari is not running"',
        'set lim to (item 1 of argv) as integer',
        'set TB to character id 9',
        'tell application "Safari"',
        '  if (count of windows) = 0 then return "no Safari window open"',
        '  set out to {}',
        '  set n to 0',
        '  set total to 0',
        '  repeat with wi from 1 to count of windows',
        '    set w to window wi',
        '    try',
        '      set ci to index of current tab of w',
        '      set ts to tabs of w',
        '    on error',
        '      set ts to {}',
        '    end try',
        '    repeat with ti from 1 to count of ts',
        '      set total to total + 1',
        '      if n < lim then',
        '        set t to item ti of ts',
        '        if ti = ci then',
        '          set m to "*"',
        '        else',
        '          set m to ""',
        '        end if',
        '        set u to my cl(URL of t)',
        '        if (count of u) > 300 then set u to (text 1 thru 300 of u) & "…"',
        '        set end of out to (wi as text) & TB & (ti as text) & TB & m & TB & my cl(name of t) & TB & u',
        '        set n to n + 1',
        '      end if',
        '    end repeat',
        '  end repeat',
        'end tell',
        'if total > n then set end of out to "… " & ((total - n) as text) & " more tabs not shown"',
        'set AppleScript\'s text item delimiters to linefeed',
        'return out as text',
        'end run',
        ...CL,
      ]),
      args: [String(limit ?? 100)],
    }),
  },
  {
    name: 'safari_activate_tab',
    description: 'Bring a Safari tab to the front by window and tab index (from safari_list_tabs); returns its title.',
    schema: {
      window: z.number().int().min(1).max(1000).describe('Window index, 1-based (see safari_list_tabs)'),
      tab: z.number().int().min(1).max(1000).describe('Tab index, 1-based (see safari_list_tabs)'),
    },
    build: ({ window, tab }) => ({
      script: as([
        'on run argv',
        'if not (application "Safari" is running) then return "Safari is not running"',
        'set wi to (item 1 of argv) as integer',
        'set ti to (item 2 of argv) as integer',
        'tell application "Safari"',
        '  if wi > (count of windows) then return "no window " & wi',
        '  set w to window wi',
        '  if ti > (count of tabs of w) then return "no tab " & ti & " in window " & wi',
        '  set current tab of w to tab ti of w',
        '  set index of w to 1',
        '  activate',
        '  return "activated " & (name of current tab of w)',
        'end tell',
        'end run',
      ]),
      args: [String(window), String(tab)],
    }),
  },
  {
    name: 'safari_search_web',
    description: "Search the web with Safari's current search provider, in a new tab (launches Safari if needed).",
    schema: { query: z.string().min(1).max(1000).describe('search query') },
    build: ({ query }) => ({
      script: as([
        'on run argv',
        'set q to item 1 of argv',
        'tell application "Safari"',
        '  activate',
        '  if (count of windows) = 0 then',
        '    make new document',
        '  else',
        '    tell front window to set current tab to (make new tab)',
        '  end if',
        '  search the web in current tab of front window for q',
        'end tell',
        'return "searched for " & q',
        'end run',
      ]),
      args: [query],
    }),
  },
  {
    name: 'safari_add_reading_list',
    description: 'Add an http(s) URL (optional title) to the Safari Reading List; launches Safari if needed.',
    schema: {
      url: z.string().url().refine((u) => /^https?:\/\//i.test(u), 'Only http(s) URLs are allowed').describe('http(s) URL'),
      title: z.string().max(500).optional().describe('custom title for the item'),
    },
    build: ({ url, title }) => ({
      script: as([
        'on run argv',
        'set u to item 1 of argv',
        'set t to item 2 of argv',
        'tell application "Safari"',
        '  if t is "" then',
        '    add reading list item u',
        '  else',
        '    add reading list item u with title t',
        '  end if',
        'end tell',
        'return "added to Reading List: " & u',
        'end run',
      ]),
      args: [url, title ?? ''],
    }),
  },
];
