import { z } from 'zod';
import { type Action, as, noArgs, bool } from './types.js';

/** Music.app. */
const NOT_RUNNING = 'if application "Music" is not running then return "Music is not running"';

export const musicActions: Action[] = [
  {
    name: 'music_control',
    description: 'Control Music playback (play, pause, playpause, next, previous, stop); returns the player state. play/playpause may launch Music.',
    schema: { command: z.enum(['play', 'pause', 'playpause', 'next', 'previous', 'stop']) },
    build: ({ command }) => ({
      script: as([
        'on run argv',
        'set c to item 1 of argv',
        'if c is not "play" and c is not "playpause" then',
        `  ${NOT_RUNNING}`,
        'end if',
        'tell application "Music"',
        '  if c is "play" then',
        '    play',
        '  else if c is "pause" then',
        '    pause',
        '  else if c is "playpause" then',
        '    playpause',
        '  else if c is "next" then',
        '    next track',
        '  else if c is "previous" then',
        '    previous track',
        '  else if c is "stop" then',
        '    stop',
        '  end if',
        '  return (player state as text)',
        'end tell',
        'end run',
      ]),
      args: [command],
    }),
  },
  {
    name: 'music_current_track',
    description: 'Return the current Music track (name, artist, album, position/duration in seconds) and player state.',
    schema: {},
    build: noArgs(as([
      NOT_RUNNING,
      'tell application "Music"',
      '  set pstate to player state as text',
      '  if pstate is "stopped" then return "stopped"',
      '  try',
      '    set t to current track',
      '  on error',
      '    return pstate & tab & "no current track"',
      '  end try',
      '  set pos to 0',
      '  try',
      '    set pos to round (player position) rounding down',
      '  end try',
      '  return (name of t) & tab & (artist of t) & tab & (album of t) & tab & (pos as text) & "/" & ((round (duration of t) rounding down) as text) & "s" & tab & pstate',
      'end tell',
    ])),
  },
  {
    name: 'music_list_playlists',
    description: 'List Music playlists, one per line: name and track count (default 20, max 200).',
    schema: { limit: z.number().int().min(1).max(200).optional().describe('Max playlists to return (default 20)') },
    build: ({ limit }) => ({
      script: as([
        'on run argv',
        'set lim to (item 1 of argv) as integer',
        NOT_RUNNING,
        'set out to {}',
        'tell application "Music"',
        '  set ps to playlists',
        '  set n to count of ps',
        '  repeat with i from 1 to n',
        '    if i > lim then exit repeat',
        '    set p to item i of ps',
        '    set end of out to (name of p) & tab & ((count of tracks of p) as text)',
        '  end repeat',
        'end tell',
        'if n > lim then set end of out to "(" & ((n - lim) as text) & " more not shown)"',
        "set AppleScript's text item delimiters to linefeed",
        'return out as text',
        'end run',
      ]),
      args: [String(limit ?? 20)],
    }),
  },
  {
    name: 'music_play_playlist',
    description: 'Play a Music playlist by exact name (launches Music if needed).',
    schema: { name: z.string().min(1).describe('Exact playlist name') },
    build: ({ name }) => ({
      script: as([
        'on run argv',
        'set n to item 1 of argv',
        'tell application "Music"',
        '  if not (exists playlist n) then return "no playlist named " & n',
        '  play playlist n',
        '  return "playing playlist " & n',
        'end tell',
        'end run',
      ]),
      args: [name],
    }),
  },
  {
    name: 'music_search_play',
    description: 'Search the Music library and play the first matching track; returns what is playing (launches Music if needed).',
    schema: { query: z.string().min(1).max(200).describe('Search text (song, artist, album…)') },
    build: ({ query }) => ({
      script: as([
        'on run argv',
        'set q to item 1 of argv',
        'tell application "Music"',
        '  set r to search library playlist 1 for q',
        '  if (count of r) = 0 then return "no library track matches " & q',
        '  set t to item 1 of r',
        '  play t',
        '  return "playing " & (name of t) & tab & (artist of t) & tab & (album of t)',
        'end tell',
        'end run',
      ]),
      args: [query],
    }),
  },
  {
    name: 'music_set_shuffle',
    description: 'Turn Music shuffle on or off; returns the new setting.',
    schema: { enabled: z.boolean() },
    build: ({ enabled }) => ({
      script: as([
        'on run argv',
        NOT_RUNNING,
        'tell application "Music"',
        '  set shuffle enabled to ((item 1 of argv) is "true")',
        '  return "shuffle " & (shuffle enabled as text)',
        'end tell',
        'end run',
      ]),
      args: [bool(enabled)],
    }),
  },
  {
    name: 'music_set_volume',
    description: "Set Music's own sound volume (0-100, not the system volume); returns the new level.",
    schema: { level: z.number().int().min(0).max(100).describe('Music app volume, 0-100') },
    build: ({ level }) => ({
      script: as([
        'on run argv',
        NOT_RUNNING,
        'tell application "Music"',
        '  set sound volume to ((item 1 of argv) as integer)',
        '  return "Music volume " & (sound volume as text)',
        'end tell',
        'end run',
      ]),
      args: [String(level)],
    }),
  },
];
